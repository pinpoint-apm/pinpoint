/**
 * 화면의 층(z-index) 표. `tailwind.config.js`(빌드)와 `theme.ts`(런타임)가 함께 쓴다.
 * TS 로 둔 것은 층 이름을 타입으로 한 번만 적기 위해서다. Tailwind 는 설정을 jiti 로 읽어 TS 도 읽는다.
 * `z-header`, `z-popup` 처럼 이름으로 쓴다.
 *
 * 층을 새로 쌓을 때 숫자를 하나 더 올리지 말고 여기서 자리를 정한다. 예전에는 기준 없이 그때그때
 * 숫자를 올려(1099 → 1110, 1000 → 1001, 2000 → 2001!, 5000 → 5001, 9999, 10000) 서로 이기려는
 * 경쟁이 됐다. 원인은 Radix 팝업의 기본값(`z-50`)이 화면 틀(헤더 2000, 차트 보드 1099)보다 낮았던 것이다.
 *
 * 두 묶음으로 나뉜다.
 *
 * 1. 화면 틀 — `#root` 안에서 그려지는 것. 100 미만.
 *    컴포넌트 안에서만 순서를 정하는 작은 숫자(`z-1`, `z-10`, `z-20`)는 그대로 숫자로 쓴다.
 *    이 묶음은 그보다 위에 있어야 하므로 30부터 시작한다.
 * 2. 떠 있는 것 — Radix 가 body 에 portal 로 띄우는 것과 알림. 100 이상.
 *    화면 틀의 어떤 층보다도 위다.
 *
 * 팝업끼리는 층을 나누지 않는다(모두 `popup`). Radix 는 열린 순서대로 body 끝에 붙이므로,
 * 시트 안에서 연 셀렉트·시트에서 연 다이얼로그처럼 나중에 연 것이 언제나 위에 그려진다.
 * 층을 나누면 "다이얼로그 안에서 연 셀렉트가 다이얼로그 뒤로 숨는" 식의 역전이 다시 생긴다.
 */
export const zIndexLayers = {
  // ── 화면 틀 (#root 안) ──
  /** 차트 위에 덮는 로딩·설정·경고 덮개. 차트 안의 캔버스(스캐터 가이드 등)보다 위. */
  'chart-overlay': '30',
  /** 서버맵의 우클릭 메뉴. map 버튼(`z-3`)·cytoscape 캔버스보다 위, 차트 보드보다 아래. */
  'map-menu': '40',
  /** 차트 보드 옆으로 펼쳐지는 서버 목록(rc-drawer). 라이브러리 기본값은 1050이다. */
  drawer: '50',
  /** 서버맵 우측의 차트 보드 패널. 왼쪽 map 위의 메뉴·서버 목록보다 위. */
  'chart-board': '60',
  /** 차트 보드의 크기 조절 손잡이. 패널 경계에 걸쳐 있어 패널보다 위. */
  'resize-handle': '61',
  /** 상단 헤더(sticky). 스크롤되는 화면 틀 전부보다 위. */
  header: '70',

  // ── 떠 있는 것 (body) ──
  /** popover·select·tooltip·dropdown·context menu·hover card·sheet·dialog·alert dialog 와 그 overlay. */
  popup: '100',
  /** 알림. 열려 있는 시트·다이얼로그 위에서도 보이고 눌려야 한다. */
  toast: '200',
} as const;

export type ZIndexLayer = keyof typeof zIndexLayers;
