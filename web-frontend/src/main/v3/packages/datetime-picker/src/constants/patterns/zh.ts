import { TimePattern } from '../../types';

// 중국어 상대시간. 간체·번체 어휘를 모두 매칭하고,
// 접두사 '最近'/'近'(라벨) 및 접미사 '前'/'之前'은 선택적으로 허용한다.
export const timePattern: TimePattern = {
  second: /^(最近|近)?\s*(\d+)\s*秒(\s*(前|之前))?$/,
  minute: /^(最近|近)?\s*(\d+)\s*(分钟|分鐘|分)(\s*(前|之前))?$/,
  hour: /^(最近|近)?\s*(\d+)\s*(小时|小時)(\s*(前|之前))?$/,
  day: /^(最近|近)?\s*(\d+)\s*(天|日)(\s*(前|之前))?$/,
  week: /^(最近|近)?\s*(\d+)\s*(周|週|个星期|個星期|星期)(\s*(前|之前))?$/,
  month: /^(最近|近)?\s*(\d+)\s*(个月|個月|月)(\s*(前|之前))?$/,
  year: /^(最近|近)?\s*(\d+)\s*年(\s*(前|之前))?$/,
  yesterday: /^昨天$/,
  today: /^今天$/,
  lastMonth: /^(上个月|上個月|上月)$/,
  lastYear: /^去年$/,
  unixTimestampRange: /^\d{13}\s*[^\d]\s*\d{13}$/,
};
